#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

/**
 * Generate build information including timestamp and version
 * This script runs during build to create cache invalidation data
 */
function generateBuildInfo() {
  const buildInfo = {
    buildTime: new Date().toISOString(),
    buildTimestamp: Date.now(),
    version: process.env.npm_package_version || '1.0.0',
    environment: process.env.NODE_ENV || 'development',
    gitCommit: process.env.VERCEL_GIT_COMMIT_SHA || 'local-dev',
    gitBranch: process.env.VERCEL_GIT_COMMIT_REF || 'local'
  };

  // Create public directory if it doesn't exist
  const publicDir = path.join(process.cwd(), 'public');
  if (!fs.existsSync(publicDir)) {
    fs.mkdirSync(publicDir, { recursive: true });
  }

  // Write build info to public directory (accessible via /build-info.json)
  const buildInfoPath = path.join(publicDir, 'build-info.json');
  fs.writeFileSync(buildInfoPath, JSON.stringify(buildInfo, null, 2));

  // Also write to a TypeScript file for compile-time access
  const libDir = path.join(process.cwd(), 'shared', 'lib');
  if (!fs.existsSync(libDir)) {
    fs.mkdirSync(libDir, { recursive: true });
  }

  const buildInfoTsPath = path.join(libDir, 'build-info.ts');
  const tsContent = `/**
 * Build information - auto-generated during build
 * Do not edit this file manually
 */

export const BUILD_INFO = ${JSON.stringify(buildInfo, null, 2)} as const;

export const getBuildTimestamp = () => BUILD_INFO.buildTimestamp;
export const getBuildTime = () => BUILD_INFO.buildTime;
export const getVersion = () => BUILD_INFO.version;
`;

  fs.writeFileSync(buildInfoTsPath, tsContent);

  console.log('✅ Build info generated:');
  console.log(`   Timestamp: ${buildInfo.buildTime}`);
  console.log(`   Version: ${buildInfo.version}`);
  console.log(`   Environment: ${buildInfo.environment}`);
  console.log(`   Files created:`);
  console.log(`     - ${buildInfoPath}`);
  console.log(`     - ${buildInfoTsPath}`);
}

// Run the script
try {
  generateBuildInfo();
} catch (error) {
  console.error('❌ Failed to generate build info:', error);
  process.exit(1);
}