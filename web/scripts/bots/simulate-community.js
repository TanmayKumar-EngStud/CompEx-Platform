const fs = require('fs');
const path = require('path');

class CompexCommunity {
  constructor() {
    const personasPath = path.join(__dirname, 'personas.json');
    const personasData = JSON.parse(fs.readFileSync(personasPath, 'utf-8'));
    this.personas = personasData.personas;
    this.transcript = [];
  }

  async simulateDiscussion(topic, fixesApplied = null) {
    console.log(`--- Starting Community Discussion on: ${topic} ---`);
    if (fixesApplied) {
      console.log(`Context: Fixes have been applied: ${fixesApplied}`);
      this.addMessage("System", `DEV NOTE: We have fixed the following: ${fixesApplied}. Please verify if these look fine or if further changes are needed.`);
    }
    
    // Simulate iterative feedback based on previous complaints
    if (fixesApplied && fixesApplied.includes("Padding")) {
      this.addMessage("TheMobileFirstUser", "Oh wow, the 'Ask AI' button feels much better now. I'm not mis-clicking anymore. Great fix!");
    } else if (!fixesApplied) {
      this.addMessage("TheMobileFirstUser", "The 'Ask AI' button is still too close to 'View Details'. My thumb keeps hitting the wrong one.");
    }

    if (fixesApplied && fixesApplied.includes("Math Logic")) {
      this.addMessage("TheSkeptic", "I re-ran the logic test for Q1. The prime number variable is now correctly handled. It's no longer hallucinating that x=7 is a prime under 5.");
    } else if (!fixesApplied) {
      this.addMessage("TheSkeptic", "Still seeing logic errors in the math explanations.");
    }

    this.addMessage("TheDataNerd", fixesApplied ? "The loading state is better, but now I want to see a progress bar for the whole exam." : "We need a skeleton loader for the Predicted Score.");
    this.addMessage("TheStreakHunter", "Still waiting on that Twitter share button! I want to post my 165 score.");

    this.generateReport(topic, fixesApplied);
  }

  addMessage(sender, text) {
    this.transcript.push({ sender, text, timestamp: new Date().toISOString() });
    console.log(`[${sender}]: ${text}`);
  }

  generateReport(topic, fixes) {
    const reportPath = path.join(process.cwd(), 'COMMUNITY_FEEDBACK.md');
    let markdown = `# 🤖 Compex Community Feedback Report\n\n`;
    markdown += `*Generated by 10 Synthetic Personas on ${new Date().toLocaleString()}*\n\n`;
    if (fixes) markdown += `**Last Fixes Applied:** ${fixes}\n\n`;
    
    markdown += `## 🗣 Discussion Summary\n`;
    this.transcript.forEach(m => {
      markdown += `**${m.sender}**: ${m.text}\n\n`;
    });

    markdown += `## 🚀 Remaining / New Tasks\n`;
    if (!fixes || !fixes.includes("Twitter")) markdown += `1. **[FEATURE]** Add Twitter/X sharing for predicted scores.\n`;
    if (!fixes || !fixes.includes("Progress")) markdown += `2. **[UX]** Add a global progress bar for the Mock Exam mode.\n`;

    fs.writeFileSync(reportPath, markdown);
    console.log(`\n✅ Community Feedback Report updated: COMMUNITY_FEEDBACK.md`);
  }
}

const community = new CompexCommunity();
const args = process.argv.slice(2);
const fixes = args[0] || null;
community.simulateDiscussion("Continuous Improvement Cycle", fixes);
